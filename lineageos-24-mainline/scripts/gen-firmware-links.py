#!/usr/bin/env python3
"""Write device/zte/axon7m/firmware/Android.bp: /vendor/firmware symlinks to
the phone's own firmware, so that no ZTE/Qualcomm image is part of the build.

  /mnt/vendor/firmware_mnt  = the modem partition (NON-HLOS, vfat, fstab)
  /mnt/vendor/fw_vendor     = the GPT "vendor" partition of the LineageOS
                              16-22.2 layout (ext4, a530_zap for the GPU)

The kernel loads qcom/msm8996/zte/axon7/<name>.mbn (device tree names);
a symlink to <name>.mdt makes qcom_mdt_load read the split image and ask
for <name>.bNN next to it, so every segment number gets a link too (links
to segments a firmware version does not have are never asked for).
Run from lineageos-24-mainline/: scripts/gen-firmware-links.py
"""
import os

M = "/mnt/vendor/firmware_mnt/image"
V = "/mnt/vendor/fw_vendor/firmware"
D = "firmware/qcom/msm8996/zte/axon7"
SEGS = 32
links = []  # (installed_location, target)
for name, src, segs in (("adsp", M, SEGS), ("modem", M, SEGS), ("slpi", M, SEGS),
                        ("venus", M, SEGS), ("a530_zap", V, 8)):
    links.append((f"{D}/{name}.mbn", f"{src}/{name}.mdt"))
    links += [(f"{D}/{name}.b{i:02d}", f"{src}/{name}.b{i:02d}") for i in range(segs)]
links.append((f"{D}/mba.mbn", f"{M}/mba.mbn"))
# Wi-Fi board data: the phone's calibration (bdwlan30.bin)
links.append(("firmware/ath10k/QCA6174/hw3.0/board.bin", f"{M}/bdwlan30.bin"))

out = ["// Generated by scripts/gen-firmware-links.py, do not edit.",
       "// /vendor/firmware links into the phone's own firmware partitions.", ""]
names = []
for loc, tgt in links:
    n = "axon7m_fw_" + loc.split("/", 1)[1].replace("/", "_").replace(".", "_")
    names.append(n)
    out += ["install_symlink {", f'    name: "{n}",', f'    installed_location: "{loc}",',
            f'    symlink_target: "{tgt}",', "    vendor: true,", "}", ""]
out += ["phony {", '    name: "axon7m-firmware-links",', "    required: ["]
out += [f'        "{n}",' for n in names]
out += ["    ],", "}", ""]
p = os.path.join("device/zte/axon7m/firmware/Android.bp")
open(p, "w").write("\n".join(out))
print(f"{p}: {len(names)} links")
