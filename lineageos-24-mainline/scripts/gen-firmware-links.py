#!/usr/bin/env python3
"""Write device/zte/axon7m/firmware/Android.bp: /vendor/firmware symlinks to
the phone's own firmware, so that no ZTE/Qualcomm image is part of the build.

The kernel asks for qcom/msm8996/zte/axon7/<name>.mbn
(firmware_class.path=/vendor/firmware in BoardConfig.mk). A symlink to
<name>.mdt makes qcom_mdt_load read the split image and ask for <name>.bNN
next to it, so every segment number gets a link too (links to segments a
firmware version does not have are never asked for).

The GPU's a530_zap depends on the flavour:

  standalone (default, CI release zip): /metadata is the stock `cache`
      partition, formatted ext4 by update-binary, which stages a530_zap.*
      in /metadata/axon7-fw first. The links point there. Phones with the
      LineageOS 16-22.2 `vendor` partition use it as the preferred source
      for that copy, but the built links work without it too.
  multiboot (developer builds, AXON7_MULTIBOOT=1): the GPT vendor partition
      is mounted read-only at /mnt/vendor/fw_vendor by fstab.axon7m.

The other links always point into the modem partition:
  /mnt/vendor/firmware_mnt (NON-HLOS, vfat, fstab).

Usage (from the checkout root):
  scripts/gen-firmware-links.py --flavour standalone
  scripts/gen-firmware-links.py --flavour multiboot -o /path/to/Android.bp
  scripts/gen-firmware-links.py --flavour standalone --dry-run   # list links
"""
import argparse
import os

M = "/mnt/vendor/firmware_mnt/image"
V_MULTIBOOT = "/mnt/vendor/fw_vendor/firmware"
V_STANDALONE = "/metadata/axon7-fw"
D = "firmware/qcom/msm8996/zte/axon7"
SEGS = 32
DEFAULT_OUTPUT = "device/zte/axon7m/firmware/Android.bp"


def make_links(flavour):
    v = V_STANDALONE if flavour == "standalone" else V_MULTIBOOT
    links = []
    for name, src, segs in (("adsp", M, SEGS), ("modem", M, SEGS),
                            ("slpi", M, SEGS), ("venus", M, SEGS),
                            ("a530_zap", v, 8)):
        links.append((f"{D}/{name}.mbn", f"{src}/{name}.mdt"))
        links += [(f"{D}/{name}.b{i:02d}", f"{src}/{name}.b{i:02d}")
                  for i in range(segs)]
    links.append((f"{D}/mba.mbn", f"{M}/mba.mbn"))
    # Wi-Fi board data: the phone's calibration (bdwlan30.bin)
    links.append(("firmware/ath10k/QCA6174/hw3.0/board.bin", f"{M}/bdwlan30.bin"))
    return links


def render(flavour, links):
    out = ["// Generated by scripts/gen-firmware-links.py, do not edit.",
           f"// Flavour: {flavour}. /vendor/firmware links into the phone's own",
           "// firmware partitions (standalone: /metadata/axon7-fw staged by the",
           "// installer; multiboot: /mnt/vendor/fw_vendor).", ""]
    names = []
    for loc, tgt in links:
        n = "axon7m_fw_" + loc.split("/", 1)[1].replace("/", "_").replace(".", "_")
        names.append(n)
        out += ["install_symlink {", f'    name: "{n}",',
                f'    installed_location: "{loc}",',
                f'    symlink_target: "{tgt}",', "    vendor: true,", "}", ""]
    out += ["phony {", '    name: "axon7m-firmware-links",', "    required: ["]
    out += [f'        "{n}",' for n in names]
    out += ["    ],", "}", ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--flavour", choices=("standalone", "multiboot"),
                    default="standalone",
                    help="standalone (default) or developer multiboot firmware links")
    ap.add_argument("-o", "--output", default=DEFAULT_OUTPUT,
                    help=f"Android.bp to write (default: {DEFAULT_OUTPUT})")
    ap.add_argument("--dry-run", action="store_true",
                    help="print 'installed location -> target' instead of writing")
    a = ap.parse_args()
    links = make_links(a.flavour)
    if a.dry_run:
        for loc, tgt in links:
            print(f"/vendor/{loc} -> {tgt}")
        return
    text = render(a.flavour, links)
    os.makedirs(os.path.dirname(a.output) or ".", exist_ok=True)
    with open(a.output, "w") as f:
        f.write(text)
    print(f"{a.output}: {len(links)} links ({a.flavour})")


if __name__ == "__main__":
    main()
